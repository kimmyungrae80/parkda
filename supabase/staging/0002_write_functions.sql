-- PARKDA 2.0 staging: 쓰기 함수 (parkda-staging 전용, 운영 적용 금지)
-- 0001 의 RLS 는 직접 쓰기 정책을 두지 않는다 (승인·참가·점수 입력은 아래 함수로만 기록).
-- 모든 함수는 auth.uid() 로 호출자를 확인하고, 권한·정원·점수 범위를 DB 안에서 검증한다.

-- 0001 에 없던 컬럼 (경기 홀 수, 대기 순서, 경기 참가자)
alter table public.games add column if not exists holes smallint not null default 9 check (holes in (9, 18, 27, 36));
alter table public.games add column if not exists players uuid[] not null default '{}';
alter table public.meetup_participants add column if not exists seq bigint generated by default as identity;

-- ── 동호회 가입 ──
create or replace function public.request_join(p_club uuid) returns text
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); cur text;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if not exists (select 1 from public.clubs where id = p_club) then raise exception 'club_not_found'; end if;
  select status into cur from public.club_members where club_id = p_club and user_id = me;
  if cur in ('pending', 'approved') then return cur; end if;
  insert into public.club_members (club_id, user_id, role, status) values (p_club, me, 'member', 'pending')
    on conflict (club_id, user_id) do update set status = 'pending', role = 'member';
  return 'pending';
end $$;

create or replace function public.decide_member(p_club uuid, p_user uuid, p_approve boolean) returns text
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); res text := case when p_approve then 'approved' else 'rejected' end;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if not public.is_club_staff(p_club) then raise exception 'forbidden'; end if;
  update public.club_members set status = res where club_id = p_club and user_id = p_user and status = 'pending';
  if not found then raise exception 'not_pending'; end if;
  insert into public.admin_audit_logs (actor, action, target) values (me, 'member_' || res, p_club::text || ':' || p_user::text);
  return res;
end $$;

-- ── 함께 치기 모임 ──
create or replace function public.create_meetup(p_club uuid, p_venue text, p_date date, p_time text, p_capacity int) returns uuid
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); mid uuid;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if p_club is not null and not public.is_club_staff(p_club) then raise exception 'forbidden'; end if;
  if p_capacity not between 2 and 4 then raise exception 'invalid_capacity'; end if;
  insert into public.meetups (club_id, creator, venue_id, meet_date, meet_time, capacity)
    values (p_club, me, p_venue, p_date, p_time, p_capacity) returning id into mid;
  insert into public.meetup_participants (meetup_id, user_id, status) values (mid, me, 'joined');
  return mid;
end $$;

-- 정원 확인은 모임 행을 잠근 뒤 한다 (동시 신청이 와도 정원을 넘지 않음)
create or replace function public.join_meetup(p_meetup uuid) returns text
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); m public.meetups; cur text; active int; v text;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  select * into m from public.meetups where id = p_meetup for update;
  if not found then raise exception 'meetup_not_found'; end if;
  if m.club_id is not null and not public.is_club_member(m.club_id) then raise exception 'forbidden'; end if;
  if m.status <> 'open' then raise exception 'closed'; end if;
  select status into cur from public.meetup_participants where meetup_id = p_meetup and user_id = me;
  if cur in ('joined', 'confirmed', 'waitlisted') then raise exception 'duplicate'; end if;
  select count(*) into active from public.meetup_participants where meetup_id = p_meetup and status in ('joined', 'confirmed');
  v := case when active < m.capacity then 'joined' else 'waitlisted' end;
  insert into public.meetup_participants (meetup_id, user_id, status) values (p_meetup, me, v)
    on conflict (meetup_id, user_id) do update set status = excluded.status, seq = default;
  return v;
end $$;

-- 참가 취소. 확정·참가 중이던 사람이 빠지면 가장 먼저 기다린 대기자 한 명을 올린다.
create or replace function public.cancel_join(p_meetup uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); was text; promoted uuid;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  perform 1 from public.meetups where id = p_meetup for update;
  select status into was from public.meetup_participants where meetup_id = p_meetup and user_id = me
    and status in ('joined', 'confirmed', 'waitlisted');
  if was is null then raise exception 'not_joined'; end if;
  update public.meetup_participants set status = 'cancelled' where meetup_id = p_meetup and user_id = me;
  if was in ('joined', 'confirmed') then
    update public.meetup_participants set status = 'joined', seq = default
      where meetup_id = p_meetup and user_id = (
        select user_id from public.meetup_participants where meetup_id = p_meetup and status = 'waitlisted' order by seq limit 1)
      returning user_id into promoted;
  end if;
  return promoted;
end $$;

-- ── 경기 (자동 조편성 결과 저장, 점수 입력, 중단·재개, 결과 확정) ──
create or replace function public.create_game(p_club uuid, p_meetup uuid, p_holes int, p_players uuid[]) returns uuid
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); gid uuid;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if p_club is not null and not public.is_club_staff(p_club) then raise exception 'forbidden'; end if;
  if p_holes not in (9, 18, 27, 36) then raise exception 'invalid_holes'; end if;
  if coalesce(array_length(p_players, 1), 0) < 2 then raise exception 'too_few_players'; end if;
  insert into public.games (meetup_id, club_id, holes, players, created_by)
    values (p_meetup, p_club, p_holes, p_players, me) returning id into gid;
  return gid;
end $$;

create or replace function public.set_game_paused(p_game uuid, p_paused boolean) returns text
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); g public.games; res text;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  select * into g from public.games where id = p_game for update;
  if not found then raise exception 'game_not_found'; end if;
  if g.created_by <> me then raise exception 'forbidden'; end if;
  if p_paused and g.status = 'in_progress' then res := 'paused';
  elsif not p_paused and g.status = 'paused' then res := 'in_progress';
  else raise exception 'invalid_transition'; end if;
  update public.games set status = res where id = p_game;
  insert into public.score_audit_logs (game_id, actor, action, detail) values (p_game, me, res, '{}'::jsonb);
  return res;
end $$;

-- 점수 입력: 경기 생성자 또는 같은 동호회 운영자만. 중단·확정 상태에서는 입력 불가. 변경 전 값을 이력에 남긴다.
create or replace function public.submit_score(p_game uuid, p_player uuid, p_hole int, p_strokes int) returns int
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); g public.games; old int;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  select * into g from public.games where id = p_game for update;
  if not found then raise exception 'game_not_found'; end if;
  if g.created_by <> me and not (g.club_id is not null and public.is_club_staff(g.club_id)) then raise exception 'forbidden'; end if;
  if g.status <> 'in_progress' then raise exception 'game_not_editable'; end if;
  if not (p_player = any (g.players)) then raise exception 'unknown_player'; end if;
  if p_hole not between 1 and g.holes then raise exception 'invalid_hole'; end if;
  if p_strokes not between 1 and 15 then raise exception 'invalid_strokes'; end if;
  select strokes into old from public.game_scores where game_id = p_game and player_id = p_player and hole = p_hole;
  insert into public.game_scores (game_id, player_id, hole, strokes) values (p_game, p_player, p_hole, p_strokes)
    on conflict (game_id, player_id, hole) do update set strokes = excluded.strokes;
  insert into public.score_audit_logs (game_id, actor, action, detail)
    values (p_game, me, 'score', jsonb_build_object('player', p_player, 'hole', p_hole, 'from', old, 'to', p_strokes));
  return old;
end $$;

-- 결과 확정: 모든 참가자의 전체 홀 점수가 있어야 한다. 총타수 순 순위를 돌려준다 (동점은 같은 순위).
create or replace function public.confirm_result(p_game uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); g public.games; missing int; res jsonb;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  select * into g from public.games where id = p_game for update;
  if not found then raise exception 'game_not_found'; end if;
  if g.created_by <> me then raise exception 'forbidden'; end if;
  if g.status = 'final' then raise exception 'already_final'; end if;
  select count(*) into missing from unnest(g.players) p
    where (select count(*) from public.game_scores s where s.game_id = p_game and s.player_id = p) < g.holes;
  if missing > 0 then raise exception 'incomplete_scores'; end if;
  update public.games set status = 'final' where id = p_game;
  insert into public.score_audit_logs (game_id, actor, action, detail) values (p_game, me, 'final', '{}'::jsonb);
  select jsonb_agg(r order by r.rank) into res from (
    select player_id, total, rank() over (order by total) as rank from (
      select p as player_id, (select sum(strokes) from public.game_scores s where s.game_id = p_game and s.player_id = p)::int as total
      from unnest(g.players) p) t) r;
  return res;
end $$;

-- 확정 후 수정: 생성자가 사유와 함께 잠금을 풀면 다시 입력할 수 있다. 풀린 기록은 이력에 남는다.
create or replace function public.unlock_final(p_game uuid, p_reason text) returns text
language plpgsql security definer set search_path = public as $$
declare me uuid := auth.uid(); g public.games;
begin
  if me is null then raise exception 'not_authenticated'; end if;
  if p_reason is null or char_length(p_reason) < 2 then raise exception 'reason_required'; end if;
  select * into g from public.games where id = p_game for update;
  if not found then raise exception 'game_not_found'; end if;
  if g.created_by <> me then raise exception 'forbidden'; end if;
  if g.status <> 'final' then raise exception 'not_final'; end if;
  update public.games set status = 'in_progress' where id = p_game;
  insert into public.score_audit_logs (game_id, actor, action, detail) values (p_game, me, 'unlock', jsonb_build_object('reason', p_reason));
  return 'in_progress';
end $$;

